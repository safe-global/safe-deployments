#!/usr/bin/env bash

set -euo pipefail

usage() {
    cat <<EOF
Opens a pull request with the current working-tree changes to the registry.

The branch ref and commit are created through the GitHub API rather than via
'git push', so the commit is signed by GitHub and satisfies the repository's
"require signed commits" ruleset. The new PR number is printed and, when run in
GitHub Actions, written to \$GITHUB_OUTPUT as 'pr_number' so the workflow can
dispatch the review job. (Triggering review is intentionally left to the
workflow: a PR opened with GITHUB_TOKEN does not fire the pull_request event,
but workflow_dispatch is exempt from that restriction.)

USAGE
    bash ./bin/create-registry-pr.sh <VERSION> <CHAIN_ID>

ENVIRONMENT
    GH_TOKEN            Token used by the gh CLI (required).
    GITHUB_REPOSITORY  owner/repo (defaults to safe-global/safe-deployments).
    GITHUB_RUN_ID      Used to build a unique branch name (defaults to a timestamp).
EOF
}

if [ "$#" -ne 2 ]; then
    usage
    exit 1
fi

version="$1"
chain_id="$2"

# Re-validate here too: this script is reusable and must not trust its caller to
# have sanitized the inputs. Everything below is quoted, but this is defense in
# depth for a sensitive repository.
if ! [[ "$chain_id" =~ ^[0-9]+$ ]]; then
    echo "ERROR: invalid chain id '${chain_id}' (must be numeric)." >&2
    exit 1
fi
if ! [[ "$version" =~ ^[a-zA-Z0-9.-]+$ ]]; then
    echo "ERROR: invalid version '${version}'." >&2
    exit 1
fi

repo="${GITHUB_REPOSITORY:-safe-global/safe-deployments}"
run_id="${GITHUB_RUN_ID:-$(date +%s)}"

branch="update-registry-${run_id}-${chain_id}"
title="Add chain ${chain_id} to ${version} registry"
base_sha="$(git rev-parse HEAD)"

# Collect the working-tree changes as GraphQL fileChanges. Scoped to src/assets:
# the update-registry script writes nowhere else, so this bounds the signed commit
# to registry files and prevents any stray file from riding along. Files that
# still exist on disk are additions (base64-encoded); the rest are deletions.
additions='[]'
deletions='[]'
while IFS= read -r path; do
    [ -z "$path" ] && continue
    if [ -f "$path" ]; then
        additions="$(jq -c --arg p "$path" --arg c "$(base64 -w0 "$path")" \
            '. + [{path: $p, contents: $c}]' <<<"$additions")"
    else
        deletions="$(jq -c --arg p "$path" '. + [{path: $p}]' <<<"$deletions")"
    fi
done < <(git status --porcelain -- src/assets | cut -c4-)

if [ "$additions" = '[]' ] && [ "$deletions" = '[]' ]; then
    echo "ERROR: no changes under src/assets to commit." >&2
    exit 1
fi

# Create the branch off the checked-out base commit. No new commit here, so the
# "require signed commits" ruleset is not triggered by this ref.
gh api "repos/${repo}/git/refs" -f ref="refs/heads/${branch}" -f sha="${base_sha}"

# Create the commit through the API so GitHub signs it (verified).
commit_input="$(jq -n \
    --arg repo "$repo" \
    --arg branch "$branch" \
    --arg headline "$title" \
    --arg body "Added chain ID ${chain_id} to all contracts in version ${version}." \
    --arg oid "$base_sha" \
    --argjson additions "$additions" \
    --argjson deletions "$deletions" \
    '{
        branch: {repositoryNameWithOwner: $repo, branchName: $branch},
        message: {headline: $headline, body: $body},
        expectedHeadOid: $oid,
        fileChanges: {additions: $additions, deletions: $deletions}
    }')"

jq -n \
    --arg query 'mutation ($input: CreateCommitOnBranchInput!) { createCommitOnBranch(input: $input) { commit { oid } } }' \
    --argjson input "$commit_input" \
    '{query: $query, variables: {input: $input}}' >"${RUNNER_TEMP:-/tmp}/commit.json"

commit_resp="$(gh api graphql --input "${RUNNER_TEMP:-/tmp}/commit.json")"
if jq -e '.errors' <<<"$commit_resp" >/dev/null; then
    echo "createCommitOnBranch failed: $commit_resp" >&2
    exit 1
fi

# Open the PR via the API (no local git state involved). The body is written to a
# file and passed with -F body=@file so its markdown (apostrophes, brackets) is
# not re-parsed by the shell.
pr_body_file="${RUNNER_TEMP:-/tmp}/pr-body.md"
cat >"$pr_body_file" <<EOF
## Add new chain

> **Automated PR:** This PR was generated by the Update Registry workflow. Ensure that the contracts are deployed on the chain. The RPC will be taken from [DefiLlama's ChainList](https://chainlist.org/).

Please fill the following form:

Provide the Chain ID (Only 1 chain id per PR).
- Chain_ID: ${chain_id}
EOF

pr_number="$(gh api "repos/${repo}/pulls" \
    -f title="$title" \
    -f head="$branch" \
    -f base=main \
    -F body=@"$pr_body_file" \
    --jq '.number')"
echo "Created PR #${pr_number}"

# Emit the PR number for the workflow to consume.
if [ -n "${GITHUB_OUTPUT:-}" ]; then
    echo "pr_number=${pr_number}" >>"$GITHUB_OUTPUT"
fi
